'use strict';

const crypto = require('crypto');
const config = require('../config');

const UPPERCASE = 'ABCDEFGHJKLMNPQRSTUVWXYZ'; // Exclude ambiguous I, O
const LOWERCASE = 'abcdefghijkmnpqrstuvwxyz'; // Exclude ambiguous l, o
const DIGITS = '23456789';                   // Exclude ambiguous 0, 1
const SPECIAL = '!@#$%^&*()-_=+';
const ALL_CHARS = UPPERCASE + LOWERCASE + DIGITS + SPECIAL;

/**
 * Generate a cryptographically secure 16-character temporary password.
 * Guarantees at least 1 uppercase, 1 lowercase, 1 digit, and 1 special symbol.
 * Uses Fisher-Yates shuffle to eliminate position bias.
 */
function generateTemporaryPassword(length = 16) {
  if (length < 8) length = 16;

  // Guarantee required character sets
  const required = [
    UPPERCASE[crypto.randomInt(0, UPPERCASE.length)],
    LOWERCASE[crypto.randomInt(0, LOWERCASE.length)],
    DIGITS[crypto.randomInt(0, DIGITS.length)],
    SPECIAL[crypto.randomInt(0, SPECIAL.length)]
  ];

  // Fill remainder from full set
  const remainingCount = length - required.length;
  const chars = [...required];
  for (let i = 0; i < remainingCount; i++) {
    chars.push(ALL_CHARS[crypto.randomInt(0, ALL_CHARS.length)]);
  }

  // Cryptographic Fisher-Yates shuffle
  for (let i = chars.length - 1; i > 0; i--) {
    const j = crypto.randomInt(0, i + 1);
    const temp = chars[i];
    chars[i] = chars[j];
    chars[j] = temp;
  }

  return chars.join('');
}

/**
 * Generates the text content of the downloadable credential TXT file.
 */
function generateCredentialTxt(user, temporaryPassword) {
  const generatedAt = new Date().toISOString().replace('T', ' ').slice(0, 19) + ' UTC';
  const portalUrl = config.portalUrl;

  return `================================================================================
AWS FIELD PRESALES COMMAND CENTRE — TEMPORARY USER CREDENTIALS
================================================================================

ATTENTION: This file contains temporary login credentials. Store it securely and
deliver it directly to the designated user. Do not transmit this file via
unencrypted or public messaging channels.

--------------------------------------------------------------------------------
USER ACCOUNT DETAILS
--------------------------------------------------------------------------------
Portal Name:                  AWS Field Presales Command Centre
User's Full Name:             ${user.full_name}
Username:                     ${user.username}
Corporate Email:              ${user.email}
Designation:                  ${user.designation || 'Not specified'}
Location:                     ${user.location || 'Not specified'}

--------------------------------------------------------------------------------
TEMPORARY CREDENTIALS
--------------------------------------------------------------------------------
Temporary Password:           ${temporaryPassword}
First-Login Policy:           MANDATORY PASSWORD CHANGE REQUIRED UPON FIRST LOGIN

--------------------------------------------------------------------------------
PERMISSIONS & APPLICATION ACCESS
--------------------------------------------------------------------------------
Assigned Role:                ${user.role}
Account Status:               ${user.status}
AWS Tech Horizon Access:      ${user.tech_horizon_access ? 'GRANTED' : 'DENIED'}
Monthly Report Gen Access:    ${user.monthly_report_access ? 'GRANTED' : 'DENIED'}

--------------------------------------------------------------------------------
LOGIN INSTRUCTIONS
--------------------------------------------------------------------------------
1. Open the secure Command Centre portal in your web browser:
   ${portalUrl}/login

2. Enter your Username and the Temporary Password shown above.

3. You will immediately be prompted to change your password to a private,
   permanent password of your choice (minimum 8 characters).

4. Once updated, you will access your Command Centre Launchpad.

--------------------------------------------------------------------------------
Security Notice: Generated by ${config.initialAdmin.fullName} on ${generatedAt}.
================================================================================
`;
}

